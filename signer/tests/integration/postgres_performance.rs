//! Postgres query-plan measurements.

use std::time::Duration;
use std::time::Instant;

use signer::WITHDRAWAL_FINALITY_MIN_BITCOIN_BLOCKS;
use signer::WITHDRAWAL_FINALITY_MIN_STACKS_BLOCKS;
use signer::storage::DbRead as _;
use signer::storage::model::BitcoinBlockHeight;
use signer::storage::model::StacksBlockHash;
use signer::storage::postgres::GET_WITHDRAWAL_FINALITY_HEIGHT_QUERY;
use signer::storage::postgres::PgStore;
use signer::testing;

/// The Bitcoin height of the newest block in the measurement.
const BITCOIN_CHAIN_TIP_HEIGHT: i64 = 1_006;

/// The Bitcoin anchor height of the first generated Stacks tenure.
const FIRST_TENURE_ANCHOR_HEIGHT: i64 = 800;

/// The height of the newest generated Stacks block.
const STACKS_CHAIN_TIP_HEIGHT: i64 = 100_499;

/// The number of Stacks blocks generated for each tenure.
const STACKS_BLOCKS_PER_TENURE: i64 = 500;

/// The height of the newest block in the production-scale Stacks fixture.
const PRODUCTION_SCALE_STACKS_CHAIN_TIP_HEIGHT: i64 = 9_999_999;

/// The Bitcoin chain tip needed to confirm the production-scale fixture's
/// newest Stacks tenure.
const PRODUCTION_SCALE_BITCOIN_CHAIN_TIP_HEIGHT: i64 = FIRST_TENURE_ANCHOR_HEIGHT
    + PRODUCTION_SCALE_STACKS_CHAIN_TIP_HEIGHT / STACKS_BLOCKS_PER_TENURE
    + 6;

/// The maximum acceptable runtime for the warmed production-scale query.
const MAX_PRODUCTION_SCALE_QUERY_DURATION: Duration = Duration::from_secs(1);

/// Return the hash generated by the SQL fixture for a block at `height`.
fn stacks_block_hash(height: i64) -> StacksBlockHash {
    let value = u64::try_from(height + 1).unwrap();
    let mut bytes = [0; 32];
    bytes[24..].copy_from_slice(&value.to_be_bytes());
    bytes.into()
}

/// Populate a canonical Bitcoin chain through `chain_tip_height`.
async fn populate_bitcoin_blocks(db: &PgStore, chain_tip_height: i64) {
    let result = sqlx::query(
        r#"
        INSERT INTO sbtc_signer.bitcoin_blocks (
            block_hash
          , block_height
          , parent_hash
          , is_canonical
        )
        SELECT
            decode(lpad(to_hex(height + 1), 64, '0'), 'hex')
          , height
          , decode(lpad(to_hex(height), 64, '0'), 'hex')
          , TRUE
        FROM generate_series(0, $1::BIGINT) AS height
        "#,
    )
    .bind(chain_tip_height)
    .execute(db.pool())
    .await
    .unwrap();

    let expected_rows = u64::try_from(chain_tip_height + 1).unwrap();
    assert_eq!(result.rows_affected(), expected_rows);
}

/// Populate a linear Stacks chain through `chain_tip_height`.
async fn populate_stacks_blocks(db: &PgStore, chain_tip_height: i64) {
    let result = sqlx::query(
        r#"
        INSERT INTO sbtc_signer.stacks_blocks (
            block_hash
          , block_height
          , parent_hash
          , bitcoin_anchor
        )
        SELECT
            decode(lpad(to_hex(height + 1), 64, '0'), 'hex')
          , height
          , decode(lpad(to_hex(height), 64, '0'), 'hex')
          , decode(
                lpad(
                    to_hex($2::BIGINT + height / $3::BIGINT + 1),
                    64,
                    '0'
                ),
                'hex'
            )
        FROM generate_series(0, $1::BIGINT) AS height
        "#,
    )
    .bind(chain_tip_height)
    .bind(FIRST_TENURE_ANCHOR_HEIGHT)
    .bind(STACKS_BLOCKS_PER_TENURE)
    .execute(db.pool())
    .await
    .unwrap();

    let expected_rows = u64::try_from(chain_tip_height + 1).unwrap();
    assert_eq!(result.rows_affected(), expected_rows);
}

/// Update the query planner's statistics for the generated block tables.
async fn analyze_block_tables(db: &PgStore) {
    sqlx::query("ANALYZE sbtc_signer.bitcoin_blocks")
        .execute(db.pool())
        .await
        .unwrap();
    sqlx::query("ANALYZE sbtc_signer.stacks_blocks")
        .execute(db.pool())
        .await
        .unwrap();
}

/// Execute and return the withdrawal-finality query plan.
async fn get_withdrawal_finality_query_plan(
    db: &PgStore,
    stacks_chain_tip: StacksBlockHash,
) -> Vec<String> {
    let explain_query =
        format!("EXPLAIN (ANALYZE, BUFFERS, FORMAT TEXT)\n{GET_WITHDRAWAL_FINALITY_HEIGHT_QUERY}");
    sqlx::query_scalar::<_, String>(&explain_query)
        .bind(stacks_chain_tip)
        .bind(i64::try_from(WITHDRAWAL_FINALITY_MIN_BITCOIN_BLOCKS).unwrap())
        .bind(WITHDRAWAL_FINALITY_MIN_STACKS_BLOCKS)
        .fetch_all(db.pool())
        .await
        .unwrap()
}

/// Print the query plan for finding the withdrawal finality height in a
/// database with a long Stacks history.
///
/// The fixture contains 100,500 Stacks blocks but only requires the query
/// to visit the 500 blocks in the checkpoint tenure and the first block of
/// its parent tenure. The output is intended for manual inspection, so this
/// test is ignored by default. The correctness query below warms the cache
/// before we collect the plan.
#[ignore = "measures and prints the withdrawal finality query plan"]
#[tokio::test]
async fn withdrawal_finality_query_plan() {
    let db = testing::storage::new_test_database().await;

    populate_bitcoin_blocks(&db, BITCOIN_CHAIN_TIP_HEIGHT).await;
    populate_stacks_blocks(&db, STACKS_CHAIN_TIP_HEIGHT).await;
    analyze_block_tables(&db).await;

    let stacks_chain_tip = stacks_block_hash(STACKS_CHAIN_TIP_HEIGHT);
    let finality_height = db
        .get_withdrawal_finality_height(&stacks_chain_tip, WITHDRAWAL_FINALITY_MIN_BITCOIN_BLOCKS)
        .await
        .unwrap();

    assert_eq!(finality_height, Some(BitcoinBlockHeight::from(999u64)));

    let query_plan = get_withdrawal_finality_query_plan(&db, stacks_chain_tip).await;

    println!("\n{}\n", query_plan.join("\n"));

    testing::storage::drop_db(db).await;
}

/// Check that the withdrawal-finality query remains fast with a
/// production-scale Stacks history.
///
/// This test inserts ten million Stacks blocks with 500 blocks per tenure.
/// The long tenures make the recursive walk more expensive while the full
/// history gives the primary-key indexes production-scale cardinality. It
/// is ignored by default because populating the fixture is expensive. The
/// query is warmed before it is timed so that this test measures the walk
/// and index lookups rather than filesystem cache state.
#[ignore = "populates ten million Stacks blocks to measure withdrawal finality query latency"]
#[tokio::test]
async fn withdrawal_finality_query_handles_ten_million_stacks_blocks() {
    let db = testing::storage::new_test_database().await;

    populate_bitcoin_blocks(&db, PRODUCTION_SCALE_BITCOIN_CHAIN_TIP_HEIGHT).await;
    populate_stacks_blocks(&db, PRODUCTION_SCALE_STACKS_CHAIN_TIP_HEIGHT).await;
    analyze_block_tables(&db).await;

    let stacks_chain_tip = stacks_block_hash(PRODUCTION_SCALE_STACKS_CHAIN_TIP_HEIGHT);
    let expected_height = FIRST_TENURE_ANCHOR_HEIGHT
        + PRODUCTION_SCALE_STACKS_CHAIN_TIP_HEIGHT / STACKS_BLOCKS_PER_TENURE
        - 1;
    let expected_height = BitcoinBlockHeight::from(u64::try_from(expected_height).unwrap());

    // Warm the query and check its result before measuring it.
    let finality_height = db
        .get_withdrawal_finality_height(&stacks_chain_tip, WITHDRAWAL_FINALITY_MIN_BITCOIN_BLOCKS)
        .await
        .unwrap();
    assert_eq!(finality_height, Some(expected_height));

    let start = Instant::now();
    let finality_height = tokio::time::timeout(
        MAX_PRODUCTION_SCALE_QUERY_DURATION,
        db.get_withdrawal_finality_height(
            &stacks_chain_tip,
            WITHDRAWAL_FINALITY_MIN_BITCOIN_BLOCKS,
        ),
    )
    .await
    .expect("the production-scale finality query should finish within one second")
    .unwrap();
    let query_duration = start.elapsed();

    assert_eq!(finality_height, Some(expected_height));

    let query_plan = get_withdrawal_finality_query_plan(&db, stacks_chain_tip).await;
    let scans_entire_stacks_table = query_plan
        .iter()
        .any(|line| line.contains("Seq Scan on stacks_blocks"));
    assert!(
        !scans_entire_stacks_table,
        "the query plan scans the entire stacks_blocks table:\n{}",
        query_plan.join("\n")
    );

    println!(
        "withdrawal finality query over 10,000,000 Stacks blocks took {query_duration:?}\n{}",
        query_plan.join("\n")
    );

    testing::storage::drop_db(db).await;
}
