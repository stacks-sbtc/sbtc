//! Postgres query-plan measurements.

use signer::WITHDRAWAL_FINALITY_MIN_BITCOIN_BLOCKS;
use signer::WITHDRAWAL_FINALITY_MIN_STACKS_BLOCKS;
use signer::storage::DbRead as _;
use signer::storage::model::BitcoinBlockHeight;
use signer::storage::model::StacksBlockHash;
use signer::storage::postgres::GET_WITHDRAWAL_FINALITY_HEIGHT_QUERY;
use signer::testing;

/// The Bitcoin height of the newest block in the measurement.
const BITCOIN_CHAIN_TIP_HEIGHT: i64 = 1_006;

/// The Bitcoin anchor height of the first generated Stacks tenure.
const FIRST_TENURE_ANCHOR_HEIGHT: i64 = 800;

/// The height of the newest generated Stacks block.
const STACKS_CHAIN_TIP_HEIGHT: i64 = 100_499;

/// The number of Stacks blocks generated for each tenure.
const STACKS_BLOCKS_PER_TENURE: i64 = 500;

/// Return the hash generated by the SQL fixture for a block at `height`.
fn stacks_block_hash(height: i64) -> StacksBlockHash {
    let value = u64::try_from(height + 1).unwrap();
    let mut bytes = [0; 32];
    bytes[24..].copy_from_slice(&value.to_be_bytes());
    bytes.into()
}

/// Print the query plan for finding the withdrawal finality height in a
/// database with a long Stacks history.
///
/// The fixture contains 100,500 Stacks blocks but only requires the query
/// to visit the 500 blocks in the checkpoint tenure and the first block of
/// its parent tenure. The output is intended for manual inspection, so this
/// test is ignored by default. The correctness query below warms the cache
/// before we collect the plan.
#[ignore = "measures and prints the withdrawal finality query plan"]
#[tokio::test]
async fn withdrawal_finality_query_plan() {
    let db = testing::storage::new_test_database().await;

    // Generate canonical Bitcoin blocks with deterministic 32-byte hashes.
    sqlx::query(
        r#"
        INSERT INTO sbtc_signer.bitcoin_blocks (
            block_hash
          , block_height
          , parent_hash
          , is_canonical
        )
        SELECT
            decode(lpad(to_hex(height + 1), 64, '0'), 'hex')
          , height
          , decode(lpad(to_hex(height), 64, '0'), 'hex')
          , TRUE
        FROM generate_series(0, $1::BIGINT) AS height
        "#,
    )
    .bind(BITCOIN_CHAIN_TIP_HEIGHT)
    .execute(db.pool())
    .await
    .unwrap();

    // Generate one linear Stacks chain with 500 blocks in each tenure.
    sqlx::query(
        r#"
        INSERT INTO sbtc_signer.stacks_blocks (
            block_hash
          , block_height
          , parent_hash
          , bitcoin_anchor
        )
        SELECT
            decode(lpad(to_hex(height + 1), 64, '0'), 'hex')
          , height
          , decode(lpad(to_hex(height), 64, '0'), 'hex')
          , decode(
                lpad(
                    to_hex($2::BIGINT + height / $3::BIGINT + 1),
                    64,
                    '0'
                ),
                'hex'
            )
        FROM generate_series(0, $1::BIGINT) AS height
        "#,
    )
    .bind(STACKS_CHAIN_TIP_HEIGHT)
    .bind(FIRST_TENURE_ANCHOR_HEIGHT)
    .bind(STACKS_BLOCKS_PER_TENURE)
    .execute(db.pool())
    .await
    .unwrap();

    sqlx::query("ANALYZE sbtc_signer.bitcoin_blocks")
        .execute(db.pool())
        .await
        .unwrap();
    sqlx::query("ANALYZE sbtc_signer.stacks_blocks")
        .execute(db.pool())
        .await
        .unwrap();

    let stacks_chain_tip = stacks_block_hash(STACKS_CHAIN_TIP_HEIGHT);
    let finality_height = db
        .get_withdrawal_finality_height(&stacks_chain_tip, WITHDRAWAL_FINALITY_MIN_BITCOIN_BLOCKS)
        .await
        .unwrap();

    assert_eq!(finality_height, Some(BitcoinBlockHeight::from(999u64)));

    let explain_query =
        format!("EXPLAIN (ANALYZE, BUFFERS, FORMAT TEXT)\n{GET_WITHDRAWAL_FINALITY_HEIGHT_QUERY}");
    let query_plan = sqlx::query_scalar::<_, String>(&explain_query)
        .bind(stacks_chain_tip)
        .bind(i64::try_from(WITHDRAWAL_FINALITY_MIN_BITCOIN_BLOCKS).unwrap())
        .bind(WITHDRAWAL_FINALITY_MIN_STACKS_BLOCKS)
        .fetch_all(db.pool())
        .await
        .unwrap();

    println!("\n{}\n", query_plan.join("\n"));

    testing::storage::drop_db(db).await;
}
